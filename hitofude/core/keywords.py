"""質問から探す語を取り出す（L-2）。

**質問は検索語ではない。** 全文検索は打った通りの並びを探す（trigram の
フレーズ一致）ので、「予算について何が決まった？」ではどのノートにも
当たらない（実測で出典 0 件だった）。

**形態素解析は入れない。** 辞書ごと抱えることになり、`.app` に数十 MB
乗る。代わりに、日本語の**漢字とカタカナの連なりは意味を担い、ひらがなは
助詞と語尾に偏る**という性質だけを使って素朴に切り出す。

**割り切り**: ひらがなだけの語（「めも」など）は拾えない。拾うと助詞で
全ノートに当たる。困ったら言葉を変えて打ち直せる（検索欄と同じ）。
"""

import re

MAX_TERMS = 4
"""問い合わせの回数がそのまま増えるので、上から数語で足りる。"""

MIN_LENGTH = 2
"""1 文字は絞れない（「何」「が」で全ノートに当たる）。"""

# 送り仮名の 1 文字は挟んで繋ぐ（「買い物」「打ち合わせ」）。ただし
# **助詞は繋がない**（「会議の議事録」を 1 語にすると当たらなくなる）
_PARTICLES = "のとがはをにでもやかへ"
_KANJI = "[一-鿿々〇]"
_BRIDGE = f"(?:(?![{_PARTICLES}])[ぁ-ん]{_KANJI}+)*"

# 漢字・カタカナ・英数字の連なり。**ひらがなだけの語は拾わない**
# （助詞と語尾に偏る）。長音符と中黒はカタカナ語の一部なので繋げる
_RUN = re.compile(
    rf"{_KANJI}+{_BRIDGE}"  # 漢字（送り仮名を 1 文字だけ挟める）
    r"|[ァ-ヺー・]+"  # カタカナ
    r"|[A-Za-z][A-Za-z0-9_-]*"  # 英字で始まる語
    r"|[0-9]+"  # 数字
)


def terms(question: str) -> list[str]:
    """探すのに使える語。**出た順のまま、重複を畳んで、数を絞る。**"""
    found: list[str] = []
    for match in _RUN.finditer(question):
        word = match.group().strip("ー・_-")
        if len(word) < MIN_LENGTH or word in found:
            continue
        found.append(word)
        if len(found) >= MAX_TERMS:
            break
    return found
